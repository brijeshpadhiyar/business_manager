// Builds the StitchIcons font from assets/icons/svg/*.svg.
//
//   cd tool/icons && npm install && npm run build
//
// 1. Strokes are converted to filled outlines (icon fonts only support fills).
// 2. fantasticon packs them into assets/fonts/StitchIcons.ttf.
// 3. lib/core/design_system/stitch_icons.g.dart gets one IconData per glyph.
// Codepoints are kept stable in codepoints.json so existing icons never move.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import SVGFixer from 'oslllo-svg-fixer';
import SVGIcons2SVGFontStream from 'svgicons2svgfont';
import svg2ttf from 'svg2ttf';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const srcDir = path.join(root, 'assets/icons/svg');
const fixedDir = path.join(here, 'build/fixed');
const outDir = path.join(here, 'build/out');
const cpFile = path.join(here, 'codepoints.json');

fs.rmSync(path.join(here, 'build'), { recursive: true, force: true });
fs.mkdirSync(fixedDir, { recursive: true });
fs.mkdirSync(outDir, { recursive: true });

await SVGFixer(srcDir, fixedDir, { showProgressBar: false, traceResolution: 1200 }).fix();

const names = fs.readdirSync(fixedDir).filter((f) => f.endsWith('.svg')).map((f) => f.slice(0, -4)).sort();
const codepoints = fs.existsSync(cpFile) ? JSON.parse(fs.readFileSync(cpFile, 'utf8')) : {};
let next = Math.max(0xe000 - 1, ...Object.values(codepoints)) + 1;
for (const n of names) if (!(n in codepoints)) codepoints[n] = next++;
fs.writeFileSync(cpFile, JSON.stringify(codepoints, null, 2) + '\n');

// svgicons2svgfont -> svg2ttf (fantasticon's own engines, called directly
// because its glob breaks on Windows paths).
const svgFont = await new Promise((resolve, reject) => {
  const stream = new SVGIcons2SVGFontStream({
    fontName: 'StitchIcons',
    fontHeight: 1000,
    normalize: true,
    descent: 0,
    log: () => {},
  });
  let out = '';
  stream.on('data', (d) => (out += d)).on('end', () => resolve(out)).on('error', reject);
  for (const n of names) {
    const glyph = fs.createReadStream(path.join(fixedDir, `${n}.svg`));
    glyph.metadata = { name: n, unicode: [String.fromCodePoint(codepoints[n])] };
    stream.write(glyph);
  }
  stream.end();
});
const ttf = svg2ttf(svgFont, {});
fs.writeFileSync(path.join(outDir, 'StitchIcons.ttf'), Buffer.from(ttf.buffer));
fs.copyFileSync(path.join(outDir, 'StitchIcons.ttf'), path.join(root, 'assets/fonts/StitchIcons.ttf'));

const camel = (s) => s.replace(/_([a-z])/g, (_, c) => c.toUpperCase());
const dart = `// GENERATED by tool/icons/build_icon_font.mjs — do not edit by hand.
// Source SVGs: assets/icons/svg/. Use these through AppIcons, not directly.
import 'package:material_ui/material_ui.dart';

abstract final class StitchIcons {
  static const String _family = 'StitchIcons';

${names.map((n) => `  static const IconData ${camel(n)} = IconData(0x${codepoints[n].toString(16)}, fontFamily: _family);`).join('\n')}

  /// Every glyph by source name (showcase / tests).
  static const Map<String, IconData> all = {
${names.map((n) => `    '${n}': ${camel(n)},`).join('\n')}
  };
}
`;
fs.writeFileSync(path.join(root, 'lib/core/design_system/stitch_icons.g.dart'), dart);
console.log(`Built ${names.length} glyphs:`, names.join(', '));
